    feedback = payload.get("feedback")
    label = "FALSE_POSITIVE" if feedback == "FALSE_ALARM" else "CONFIRMED" if feedback == "CONFIRMED" else None
    if not label:
        raise DomainError("INVALID_FEEDBACK", "feedback must be FALSE_ALARM or CONFIRMED.", status_code=422)
    from app.repositories import create_feedback
    from app.schemas import FeedbackCreate
    item = create_feedback(db, FeedbackCreate(event_id=event.id, feedback_type=label, comment="Recorded from UI", actor="operator"))
