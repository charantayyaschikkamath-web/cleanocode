@router.patch("/settings")
def ui_patch_settings(payload: dict[str, Any], request: Request):
    current = dict(request.app.state.ui_settings)
    for key in ("tariffPerKwh", "co2KgPerKwh"):
        if key in payload and payload[key] is not None and (not isinstance(payload[key], (float, int)) or payload[key] < 0):
            raise DomainError("INVALID_SETTING", f"{key} must be a non-negative number or null.", status_code=422)
    ranges = {"energyWasteWatts": (1, 100000), "waterNightFlowLitresPerMinute": (0.01, 10000),
              "persistenceMinutes": (1, 1440), "verificationDropPercent": (1, 100),
              "verificationWindowSeconds": (1, 86400), "scenarioClockMultiplier": (0.1, 1000)}
    for key, (minimum, maximum) in ranges.items():
        if key in payload:
            value = payload[key]
            if not isinstance(value, (float, int)) or not minimum <= value <= maximum:
                raise DomainError("INVALID_SETTING", f"{key} must be between {minimum} and {maximum}.", status_code=422)
    allowed = set(current)
    current.update({key: payload[key] for key in payload if key in allowed})
    request.app.state.ui_settings = current
    # Runtime updates are applied to future demo scenarios, not silently rewritten into
    # historical facts. Impact settings are also reflected in the Copilot facts bridge.
    request.app.state.settings = replace(
        request.app.state.settings,
        tariff_per_kwh=Decimal(str(current["tariffPerKwh"])) if current["tariffPerKwh"] is not None else None,
        co2_factor_kg_per_kwh=Decimal(str(current["co2KgPerKwh"])) if current["co2KgPerKwh"] is not None else None,
    )
    return dict(current)


class UiWhatIfRequest(BaseModel):
    model_config = ConfigDict(extra="ignore")
    buildingId: str = Field(min_length=1, max_length=120)
    roomId: str | None = None
    intervention: str = "REDUCE_POWER"
    durationHours: float = Field(default=2, gt=0, le=168)
    reductionPercent: float = Field(default=20, gt=0, le=100)


@router.post("/what-if")
def ui_what_if(payload: UiWhatIfRequest, db: Session = Depends(get_db), facts: FactsSnapshot = Depends(get_facts_snapshot)):
    if payload.intervention != "REDUCE_POWER":
        return {"baseline": None, "projected": None, "delta": None, "unit": "kWh",
                "costDelta": None, "co2DeltaKg": None,
                "formula": "This build currently has a deterministic power-reduction model only.",
                "assumptions": ["Water repair and schedule optimization are not implemented in this release; no result was fabricated."],
                "provenance": "UNKNOWN", "status": "UNAVAILABLE"}
    room = db.get(Room, payload.roomId) if payload.roomId else db.scalar(select(Room).where(Room.building_id == payload.buildingId).order_by(Room.name).limit(1))
    if not room or room.building_id != payload.buildingId:
        return {"baseline": None, "projected": None, "delta": None, "unit": "kWh",
                "costDelta": None, "co2DeltaKg": None,
                "formula": "A registered room and a compatible baseline are required.",
                "assumptions": ["Create a campus room or run an explicit labelled scenario first."],
                "provenance": "UNKNOWN", "status": "UNAVAILABLE"}
    request = build_single_request(room_id=room.id, duration_hours=Decimal(str(payload.durationHours)),
                                   scenario_baseline_watts=None, intervention_name="Reduce power draw",
                                   reduction_percent=Decimal(str(payload.reductionPercent)))
    estimate = calculate_comparison(request, facts)[0]
    if estimate.status.value == "UNAVAILABLE" or estimate.projected_avoided_energy_kwh is None or estimate.baseline_energy_kwh is None or estimate.projected_remaining_energy_kwh is None:
        assumptions = list(estimate.assumptions) + list(estimate.missing_inputs)
        return {"baseline": None, "projected": None, "delta": None, "unit": "kWh",
                "costDelta": None, "co2DeltaKg": None,
                "formula": "kWh = (baseline power in W / 1000) × duration in hours; no result without a valid baseline.",
                "assumptions": assumptions or ["A healthy, compatible power baseline is unavailable."],
                "provenance": "UNKNOWN", "status": "UNAVAILABLE"}
    provenance = estimate.baseline_provenance.value
    assumptions = list(estimate.assumptions) + list(estimate.missing_inputs)
    return {"baseline": float(estimate.baseline_energy_kwh),
            "projected": float(estimate.projected_remaining_energy_kwh),
            "delta": float(estimate.projected_avoided_energy_kwh), "unit": "kWh",
            "costDelta": float(estimate.projected_cost_avoided) if estimate.projected_cost_avoided is not None else None,
            "co2DeltaKg": float(estimate.projected_co2_avoided_kg) if estimate.projected_co2_avoided_kg is not None else None,
            "formula": "Baseline kWh = (power W / 1000) × duration h; avoided kWh = baseline kWh × reduction%; remaining kWh = baseline − avoided.",
            "assumptions": assumptions, "provenance": provenance,
            "status": "PROJECTED"}


