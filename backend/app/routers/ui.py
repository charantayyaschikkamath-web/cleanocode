def _iso(value: datetime | None) -> str:
    if not value:
        return ""
    return value.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")


def _num(value: Any) -> float | None:
    try:
        return float(value) if value is not None else None
    except (TypeError, ValueError, OverflowError):
        return None


def _title(event_type: str) -> str:
    return {
        "likely_energy_waste": "Likely energy waste",
        "likely_water_anomaly": "Likely water-flow anomaly",
        "likely_bin_overflow": "Likely bin overflow",
        "likely_inefficient_room_use": "Inefficient room use",
        "sensor_unavailable": "Sensor unavailable",
        "evidence_insufficient": "Evidence insufficient",
        "sensor_stale": "Sensor evidence is stale",
    }.get(event_type, event_type.replace("_", " ").capitalize())


def _status(status: str) -> str:
    return {"FALSE_POSITIVE": "FALSE_ALARM", "CLOSED": "RESOLVED"}.get(status, status)


def _reading_out(row: SensorReading, source_names: dict[str, str] | None = None) -> dict[str, Any]:
    return {
        "id": row.id, "resourceType": row.resource_type.upper(), "value": _num(row.value), "unit": row.unit,
        "observedAt": _iso(row.observed_at), "ageSeconds": row.freshness_seconds,
        "health": row.source_status if row.source_status in {"HEALTHY", "DEGRADED", "UNAVAILABLE", "UNKNOWN"} else "UNKNOWN",
        "provenance": row.provenance,
        "sourceName": row.sensor_id or row.source_type or "Unspecified source",
    }


def _event_out(db: Session, event: CampusEvent, buildings: dict[str, Building] | None = None,
               rooms: dict[str, Room] | None = None) -> dict[str, Any]:
    buildings = buildings if buildings is not None else {x.id: x for x in db.scalars(select(Building)).all()}
    rooms = rooms if rooms is not None else {x.id: x for x in db.scalars(select(Room)).all()}
    building = buildings.get(event.building_id)
    room = rooms.get(event.room_id) if event.room_id else None
    snapshot = event.evidence_snapshot or {}
    reading_ids = list(snapshot.get("reading_ids") or event.evidence_refs or [])
    by_id = {r.id: r for r in db.scalars(select(SensorReading).where(SensorReading.id.in_(reading_ids))).all()} if reading_ids else {}
    ordered = [by_id[rid] for rid in reading_ids if rid in by_id]
    evidence = []
    for index, row in enumerate(ordered):
        label = f"{row.resource_type.title()} reading"
        evidence.append({"id": row.id, "label": label, "detail": f"{row.value} {row.unit} · {_iso(row.observed_at)} · {row.provenance}", "reading": _reading_out(row)})
    thresholds = snapshot.get("thresholds") or snapshot.get("rule_inputs") or {}
    threshold = "; ".join(f"{key}: {value}" for key, value in thresholds.items()) if isinstance(thresholds, dict) and thresholds else event.trigger_rule
    limitations = []
    if event.provenance == "SIMULATED": limitations.append("This event was generated by a synthetic scenario, not a live campus meter.")
    if not ordered: limitations.append("No linked readings were found in the persisted evidence record.")
    explanation = str(snapshot.get("explanation") or snapshot.get("reason") or f"Event triggered by rule {event.trigger_rule}.")
    severity = "LOW" if event.severity == "INFO" else event.severity
    return {
        "id": event.id, "eventType": event.event_type, "severity": severity,
        "status": _status(event.status), "title": _title(event.event_type),
        "summary": explanation, "buildingId": event.building_id,
        "buildingName": building.name if building else "Unknown building",
        "roomId": event.room_id, "roomName": room.name if room else None,
        "firstSeenAt": _iso(event.first_seen_at), "updatedAt": _iso(event.last_updated_at),
        "triggerRule": event.trigger_rule, "threshold": threshold,
        "explanation": explanation, "limitations": limitations, "evidence": evidence,
        "provenance": event.provenance,
    }


def _action_out(db: Session, action: ActionRecord, buildings: dict[str, Building] | None = None,
                rooms: dict[str, Room] | None = None, events: dict[str, CampusEvent] | None = None) -> dict[str, Any]:
    buildings = buildings if buildings is not None else {x.id: x for x in db.scalars(select(Building)).all()}
    rooms = rooms if rooms is not None else {x.id: x for x in db.scalars(select(Room)).all()}
    events = events if events is not None else {x.id: x for x in db.scalars(select(CampusEvent)).all()}
    event = events.get(action.event_id)
    building = buildings.get(event.building_id) if event else None
    room = rooms.get(event.room_id) if event and event.room_id else None
    rows = list(db.scalars(select(ActionTransition).where(ActionTransition.action_id == action.id).order_by(ActionTransition.sequence_no)).all())
    verification = latest_verification(db, action.id)
    baseline = (action.metadata_json or {}).get("baseline_snapshot") or {}
    post = verification.post_action_snapshot if verification else {}
    baseline_val = _num(baseline.get("median_value", baseline.get("value")))
    observed_val = _num(post.get("median_value", post.get("value"))) if post else None
    observed_drop = ((baseline_val - observed_val) / baseline_val * 100) if baseline_val and observed_val is not None else None
    return {
        "id": action.id, "eventId": action.event_id,
        "eventTitle": _title(event.event_type) if event else "Linked event unavailable",
        "buildingName": building.name if building else "Unknown building",
        "roomName": room.name if room else None,
        "state": action.state, "createdAt": _iso(action.created_at), "updatedAt": _iso(action.updated_at),
        "proposedAction": "Simulate a power reduction and independently verify the response" if action.action_type == "SIMULATED_REDUCE_POWER" else action.action_type.replace("_", " ").title(),
        "actor": action.actor, "outcome": verification.result if verification else action.command_payload.get("outcome_mode"),
        "baselineValue": baseline_val, "observedValue": observed_val,
        "requiredDropPercent": _num((action.metadata_json or {}).get("required_drop_percent")),
        "observedDropPercent": observed_drop,
        "verificationWindowSeconds": _num((action.metadata_json or {}).get("verification_window_seconds")),
        "provenance": (action.metadata_json or {}).get("provenance", "SIMULATED"),
        "transitions": [{"id": row.id, "fromState": row.previous_state, "toState": row.new_state,
                         "at": _iso(row.occurred_at), "actor": row.actor_or_source, "note": row.note} for row in rows],
    }


def _ledger_out(row: SavingsLedgerEntry) -> dict[str, Any]:
    quantity = _num(row.energy_kwh if row.energy_kwh is not None else row.water_liters)
    unit = "kWh" if row.energy_kwh is not None else "L" if row.water_liters is not None else row.unit
    assumptions = list(row.assumptions or [])
    inputs = row.calculation_inputs or {}
    formula = str(inputs.get("formula") or f"Verified {row.resource_type.lower()} impact based on {row.calculation_version}")
    return {
        "id": row.id, "actionId": row.action_id, "eventId": str(inputs.get("event_id", "")),
        "resourceType": row.resource_type, "quantity": quantity or 0,
        "unit": unit, "estimatedCost": _num(row.cost_amount), "estimatedCo2Kg": _num(row.co2_kg),
        "formula": formula, "assumptions": assumptions,
        "observationPeriod": f"{_iso(row.observation_start)} — {_iso(row.observation_end)}",
        "provenance": "SIMULATED" if row.status == "VERIFIED_SIMULATED" else "REAL",
        "status": row.status, "createdAt": _iso(row.created_at),
    }


def _metric(value: float | None, unit: str, provenance: str = "UNKNOWN", note: str | None = None, period: str | None = None):
    return {"value": value, "unit": unit, "period": period, "provenance": provenance, "note": note or ("No compatible persisted inputs available." if value is None else None)}


def _settings(request: Request) -> dict[str, Any]:
    return dict(request.app.state.ui_settings)


