@router.post("/scenarios/run")
def ui_run_scenario(payload: UiScenarioRequest, request: Request, db: Session = Depends(get_db)):
    scenario_map = {
        "empty_room_high_power": "EMPTY_ROOM_HIGH_POWER", "night_water_flow": "NIGHT_WATER_FLOW",
        "bin_overflow": "BIN_OVERFLOW", "inefficient_room_use": "INEFFICIENT_ROOM_USE",
        "normal_operation": "NORMAL_OPERATION", "sensor_unavailable": "SENSOR_MISSING",
        "sensor_missing": "SENSOR_MISSING", "sensor_stale": "SENSOR_STALE",
        "command_dropped": "COMMAND_DROPPED", "acknowledged_ignored": "ACKNOWLEDGED_IGNORED",
        "verified_success": "VERIFIED_RESPONSE",
    }
    normalized = scenario_map.get(payload.scenario.casefold())
    if normalized is None:
        raise DomainError("UNKNOWN_SCENARIO", f"Unknown scenario: {payload.scenario}", status_code=422)
    building_id = payload.buildingId
    room_id = payload.roomId
    if building_id is None or db.get(Building, building_id) is None:
        building = db.scalar(select(Building).where(Building.code == "DEMO-BLOCK"))
        if building is None:
            building = create_building(db, BuildingCreate(name="Campus Demonstration Block", code="DEMO-BLOCK", location="Local scenario environment", metadata={"provenance": "SIMULATED"}))
        building_id = building.id
    if room_id is None or db.get(Room, room_id) is None:
        room = db.scalar(select(Room).where(Room.building_id == building_id, Room.code == "CS-LAB-01"))
        if room is None:
            room = create_room(db, RoomCreate(building_id=building_id, name="Computer Science Lab 01", code="CS-LAB-01", floor="1", capacity=40, metadata={"provenance": "SIMULATED", "created_by": "explicit scenario action"}))
        room_id = room.id
    outcome_map = {"VERIFIED_SUCCESS": "SUCCESS", "COMMAND_DROPPED": "DROP_COMMAND", "ACKNOWLEDGED_IGNORED": "ACK_IGNORE"}
    # A normal energy-waste scenario creates a pending proposal so a human must approve it.
    # SUCCESS describes the controlled simulator outcome after approval; it does not execute it now.
    outcome_mode = outcome_map.get(str(payload.outcome or "").upper(), "SUCCESS" if normalized == "EMPTY_ROOM_HIGH_POWER" else "NOT_APPLICABLE")
    if normalized == "COMMAND_DROPPED": outcome_mode = "DROP_COMMAND"
    if normalized == "ACKNOWLEDGED_IGNORED": outcome_mode = "ACK_IGNORE"
    if normalized == "VERIFIED_RESPONSE": outcome_mode = "SUCCESS"
    scenario_request = ScenarioRunRequest(
        scenario_type=normalized, building_id=building_id, room_id=room_id,
        outcome_mode=outcome_mode,
        duration_virtual_seconds=900,
        thresholds={
            "min_power_w": float(request.app.state.ui_settings["energyWasteWatts"]),
            "energy_persistence_seconds": float(request.app.state.ui_settings["persistenceMinutes"]) * 60,
            "water_flow_lpm": float(request.app.state.ui_settings["waterNightFlowLitresPerMinute"]),
            "water_persistence_seconds": float(request.app.state.ui_settings["persistenceMinutes"]) * 60,
            "required_drop_percent": float(request.app.state.ui_settings["verificationDropPercent"]),
            "verification_window_seconds": float(request.app.state.ui_settings["verificationWindowSeconds"]),
        },
    )
    result = run_scenario(db, request=scenario_request, clock=request.app.state.clock, settings=request.app.state.settings)
    event_ids = result.get("event_ids", [])
    action_id = result.get("action_ids", [None])[0] if result.get("action_ids") else None
    return {"runId": result["scenario_run_id"], "scenario": result["scenario_type"],
            "message": "The scenario ran and persisted its synthetic readings. No live campus sensors were modified.",
            "createdEventIds": event_ids, "actionId": action_id, "provenance": result.get("provenance", "SIMULATED"),
            "warnings": result.get("warnings", [])}


