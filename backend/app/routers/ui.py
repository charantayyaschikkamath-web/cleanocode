@router.get("/reports/export")
def ui_export_report(format: str = Query(default="json", pattern="^(json|csv)$"), db: Session = Depends(get_db)):
    events = list(db.scalars(select(CampusEvent).order_by(CampusEvent.first_seen_at.desc()).limit(500)).all())
    actions = list(db.scalars(select(ActionRecord).order_by(ActionRecord.created_at.desc()).limit(500)).all())
    ledger = list(db.scalars(select(SavingsLedgerEntry).order_by(SavingsLedgerEntry.created_at.desc()).limit(500)).all())
    packet = {"reportType": "CampusTwin evidence packet", "generatedAt": _iso(utc_now()),
              "notes": ["Synthetic inputs retain SIMULATED provenance.", "Projections are not measured savings.", "Only independently verified action outcomes enter the ledger."],
              "events": [{"id": x.id, "type": x.event_type, "status": x.status, "provenance": x.provenance, "firstSeenAt": _iso(x.first_seen_at)} for x in events],
              "actions": [{"id": x.id, "state": x.state, "eventId": x.event_id, "updatedAt": _iso(x.updated_at)} for x in actions],
              "ledger": [{"id": x.id, "actionId": x.action_id, "energy_kwh": _num(x.energy_kwh), "cost": _num(x.cost_amount), "co2_kg": _num(x.co2_kg), "status": x.status} for x in ledger]}
    if format == "csv":
        stream = io.StringIO()
        writer = csv.writer(stream)
        writer.writerow(["record_type", "id", "status_or_type", "provenance_or_resource", "timestamp"])
        for item in packet["events"]: writer.writerow(["event", item["id"], item["status"], item["provenance"], item["firstSeenAt"]])
        for item in packet["actions"]: writer.writerow(["action", item["id"], item["state"], "SIMULATED", item["updatedAt"]])
        for item in packet["ledger"]: writer.writerow(["ledger", item["id"], item["status"], "verified_ledger", ""])
        return Response(content=stream.getvalue(), media_type="text/csv; charset=utf-8", headers={"Content-Disposition": "attachment; filename=campustwin-evidence.csv"})
    return JSONResponse(packet, headers={"Content-Disposition": "attachment; filename=campustwin-evidence.json"})


