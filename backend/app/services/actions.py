ACTION_TERMINAL = {"VERIFIED_SUCCESS", "REJECTED", "COMMAND_FAILED", "ACK_TIMEOUT", "VERIFICATION_FAILED", "VERIFICATION_TIMEOUT"}


def _median_value(rows: list[SensorReading]) -> Decimal:
    return Decimal(str(median([float(x.value) for x in rows])))


def _compatible_energy_readings(session: Session, event: CampusEvent, preferred_ids: list[str] | None = None) -> list[SensorReading]:
    query = select(SensorReading).where(
        SensorReading.building_id == event.building_id,
        SensorReading.resource_type == "ENERGY",
        SensorReading.unit == "W",
        SensorReading.source_status == "HEALTHY",
        SensorReading.provenance == "SIMULATED",
    )
    if event.room_id:
        query = query.where(SensorReading.room_id == event.room_id)
    if preferred_ids:
        query = query.where(SensorReading.id.in_(preferred_ids))
    rows = list(session.scalars(query.order_by(SensorReading.observed_at.asc())).all())
    # Never combine sources; the action needs a single comparable meter series.
    if not rows:
        return []
    groups: dict[str, list[SensorReading]] = {}
    for item in rows:
        key = item.sensor_id or f"{item.source_type}:{item.unit}"
        groups.setdefault(key, []).append(item)
    return max(groups.values(), key=lambda values: (len(values), values[-1].observed_at))[-30:]


def create_action_proposal(session: Session, request: ActionProposalRequest, *, scenario_run_id: str | None = None) -> ActionRecord:
    event = get_event(session, request.event_id)
    if event.event_type != "likely_energy_waste":
        raise DomainError("ACTION_NOT_SUPPORTED_FOR_EVENT", "SIMULATED_REDUCE_POWER is only supported for likely_energy_waste events.", status_code=422)
    if (event.evidence_snapshot or {}).get("rule_id") != "ENERGY_EMPTY_HIGH_POWER_V1":
        raise DomainError("RULE_EVIDENCE_REQUIRED", "An action requires an event generated by the verified energy-waste rule; manually asserted event types are not sufficient.", status_code=422)
    if event.provenance != "SIMULATED":
        raise DomainError("SIMULATED_ACTION_REQUIRES_SIMULATED_EVENT", "This Account 3 adapter only executes simulated actions; no real actuator is configured.", status_code=422)

    candidate_ids = (event.evidence_snapshot or {}).get("reading_ids") or event.evidence_refs or []
    baseline_rows = _compatible_energy_readings(session, event, candidate_ids)
    if len(baseline_rows) < 3:
        raise DomainError("BASELINE_EVIDENCE_INSUFFICIENT", "A simulated action requires at least three healthy, compatible baseline power readings.", status_code=422, details={"found": len(baseline_rows), "required": 3})
    baseline_rows = baseline_rows[-3:]
    if len({x.sensor_id for x in baseline_rows}) != 1:
        raise DomainError("BASELINE_SOURCE_MISMATCH", "Baseline readings must come from the same sensor.", status_code=422)
    start, end = baseline_rows[0].observed_at, baseline_rows[-1].observed_at
    if end <= start:
        raise DomainError("BASELINE_WINDOW_INVALID", "Baseline samples must span a positive time interval.", status_code=422)
    baseline = _median_value(baseline_rows)
    if baseline <= 0:
        raise DomainError("BASELINE_NOT_COMPUTABLE", "The baseline must be greater than zero to calculate a percent change.", status_code=422)

    metadata: dict[str, Any] = {
        "provenance": "SIMULATED",
        "scenario_run_id": scenario_run_id or (event.evidence_snapshot or {}).get("scenario_run_id"),
        "outcome_mode": request.outcome_mode,
        "required_drop_percent": request.required_drop_percent,
        "verification_window_seconds": request.verification_window_seconds,
        "baseline_snapshot": {
            "reading_ids": [r.id for r in baseline_rows],
            "median_value": str(baseline),
            "unit": "W",
            "resource_type": "ENERGY",
            "sensor_id": baseline_rows[0].sensor_id,
            "sample_count": len(baseline_rows),
            "window_start": start.isoformat().replace("+00:00", "Z"),
            "window_end": end.isoformat().replace("+00:00", "Z"),
            "algorithm_version": "median-baseline-v1",
            "provenance": "SIMULATED",
        },
    }
    return create_action_record(
        session,
        event_id=event.id,
        idempotency_key=request.idempotency_key,
        action_type=request.action_type,
        actor=request.actor,
        command_payload={"simulated_power_multiplier": 0.35, "outcome_mode": request.outcome_mode},
        baseline_reading_ids=[r.id for r in baseline_rows],
        metadata=metadata,
        now=utc_now(),
    )


def get_action(session: Session, action_id: str) -> ActionRecord:
    item = session.get(ActionRecord, action_id)
    if item is None:
        raise NotFoundError("action", action_id)
    return item


def list_actions(session: Session, *, status: str | None = None, event_id: str | None = None, limit: int = 100) -> list[ActionRecord]:
    query = select(ActionRecord).order_by(ActionRecord.created_at.desc()).limit(limit)
    if status:
        query = query.where(ActionRecord.state == status)
    if event_id:
        query = query.where(ActionRecord.event_id == event_id)
    return list(session.scalars(query).all())


def list_action_transitions(session: Session, action_id: str) -> list[ActionTransition]:
    get_action(session, action_id)
    return list(session.scalars(select(ActionTransition).where(ActionTransition.action_id == action_id).order_by(ActionTransition.sequence_no.asc())).all())


def latest_verification(session: Session, action_id: str) -> VerificationRecord | None:
    get_action(session, action_id)
    return session.scalar(select(VerificationRecord).where(VerificationRecord.action_id == action_id).order_by(VerificationRecord.created_at.desc()).limit(1))


def reject_action(session: Session, *, action_id: str, actor: str, reason: str, request_key: str) -> ActionRecord:
    action = get_action(session, action_id)
    if action.state == "REJECTED":
        prior = session.scalar(select(ActionTransition).where(ActionTransition.action_id == action_id, ActionTransition.new_state == "REJECTED").order_by(ActionTransition.sequence_no.desc()).limit(1))
        if prior and prior.request_key == request_key and prior.note == reason:
            return action
        raise ConflictError("ACTION_ALREADY_TERMINAL", "This action has already been rejected.", details={"state": action.state})
    append_action_transition(
        session, action_id=action_id, new_state="REJECTED", actor_or_source=actor,
        evidence={"reason": reason}, note=reason, request_key=request_key, now=utc_now(),
    )
    return get_action(session, action_id)


def approve_action(session: Session, *, action_id: str, actor: str, request_key: str, settings, clock) -> ActionRecord:
    action = get_action(session, action_id)
    prior_dispatch = session.scalar(select(ActionTransition).where(
        ActionTransition.action_id == action_id,
        ActionTransition.new_state == "COMMAND_SENT",
        ActionTransition.request_key == request_key,
    ))
    if action.state in ACTION_TERMINAL and prior_dispatch:
        # Replayed request after completion: return persisted result without redispatching.
        return action
    if action.state != "PENDING_APPROVAL" and not prior_dispatch:
        raise ConflictError("INVALID_ACTION_TRANSITION", "Only a pending action can be approved; this request did not match its original approval key.", details={"state": action.state})

    event = get_event(session, action.event_id)
    if event.provenance != "SIMULATED" or action.action_type != "SIMULATED_REDUCE_POWER":
        raise DomainError("NO_REAL_ACTUATOR_CONFIGURED", "No real device command was sent. This implementation supports simulated power actions only.", status_code=422)

    baseline = (action.metadata_json or {}).get("baseline_snapshot") or {}
    baseline_ids = list(action.baseline_reading_ids or [])
    if len(baseline_ids) < 3 or Decimal(str(baseline.get("median_value", "0"))) <= 0:
        raise DomainError("BASELINE_EVIDENCE_INSUFFICIENT", "The immutable pre-action baseline is missing or invalid.", status_code=409)

    # Resume safely if the process stopped after writing a transition. Stable request
    # keys prevent duplicate transitions and stable reading idempotency keys prevent
    # duplicate verification samples.
    if action.state == "PENDING_APPROVAL":
        append_action_transition(
            session, action_id=action_id, new_state="COMMAND_SENT", actor_or_source=actor,
            evidence={"human_approved": True, "approval_idempotency_key": request_key, "baseline_reading_ids": baseline_ids},
            note="Human approved; simulated command dispatched.", request_key=request_key, now=clock.virtual_now(),
        )
        action = get_action(session, action_id)

    mode = action.command_payload.get("outcome_mode", "SUCCESS")
    if mode == "DROP_COMMAND":
        if action.state == "COMMAND_SENT":
            append_action_transition(
                session, action_id=action_id, new_state="ACK_TIMEOUT", actor_or_source="simulator",
                evidence={"outcome_mode": mode, "ack_received": False},
                note="The simulator dropped the command; no acknowledgement arrived.",
                request_key=f"{request_key}:ack-timeout", now=clock.virtual_now(),
            )
        return get_action(session, action_id)

    if action.state == "COMMAND_SENT":
        append_action_transition(
            session, action_id=action_id, new_state="ACKED", actor_or_source="simulator",
            evidence={"outcome_mode": mode, "ack_received": True},
            note="The simulated receiver acknowledged the command; this is not success verification.",
            request_key=f"{request_key}:acked", now=clock.virtual_now(),
        )
        action = get_action(session, action_id)
    if action.state == "ACKED":
        append_action_transition(
            session, action_id=action_id, new_state="VERIFYING", actor_or_source="verification_service",
            evidence={"baseline_reading_ids": baseline_ids, "verification_window_seconds": action.metadata_json.get("verification_window_seconds", 300)},
            note="Independent verification started using the immutable pre-action baseline.",
            request_key=f"{request_key}:verifying", now=clock.virtual_now(),
        )
        action = get_action(session, action_id)
    if action.state != "VERIFYING":
        raise ConflictError("INVALID_ACTION_TRANSITION", "The action cannot resume verification from its current state.", details={"state": action.state})

    from app.services.verification import generate_post_action_readings, finalize_verification

    post_rows = generate_post_action_readings(session, action=action, event=event, clock=clock, outcome_mode=mode)
    required_drop = Decimal(str(action.metadata_json.get("required_drop_percent", 30)))
    finalize_verification(
        session,
        action_id=action_id,
        post_rows=post_rows,
        required_drop_percent=required_drop,
        verification_window_seconds=int(action.metadata_json.get("verification_window_seconds", 300)),
        settings=settings,
        actor="verification_service",
        request_key=f"{request_key}:verification-final",
        now=clock.virtual_now(),
    )
    return get_action(session, action_id)
